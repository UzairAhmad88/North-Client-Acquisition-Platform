def validate_agent_permissions(requested_permissions: Set[str]) -> Set[str]:
    """Validate that requested permissions do not contain prohibited communication side effects."""
    for perm in requested_permissions:
        if perm in PROHIBITED_PERMISSIONS:
            raise AgentPermissionDeniedError(
                f"Permission '{perm}' is strictly prohibited. Agent runtime does not grant autonomous communication side-effects."
            )
    return requested_permissions


def check_tool_permission(agent_permissions: Set[str], required_permission: str) -> None:
    """Verify an agent holds the required permission to execute a tool."""
    if required_permission in PROHIBITED_PERMISSIONS:
        raise AgentPermissionDeniedError(
            f"Execution blocked: Required permission '{required_permission}' is prohibited."
        )

    if required_permission not in agent_permissions:
        raise AgentPermissionDeniedError(
            f"Permission Denied: Agent lacks required permission '{required_permission}'."
        )
